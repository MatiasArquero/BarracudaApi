namespace BarracudaSystem.Application.DTOs;

public class CreateItemDto //Recibir datos al crear/editar con el formulario
{
    //Datos Basicos
    public string SKU { get; set; } = string.Empty;
    public string Barcode { get; set; } = string.Empty;
    public bool IsAutoGeneratedCode { get; set; } = false;
    public string Name { get; set; } = string.Empty;
    public string Brand { get; set; } = string.Empty;

    //Clasificacion (Id para relacionarse
    public int CategoryId { get; set; }
    public int ProviderId { get; set; }

    //Finanzas e Inventario
    public decimal NetCost { get; set; }
    public bool ApplyIva { get; set; } = true;
    public decimal MarginPercentage { get; set; }
    public decimal FinalPrice { get; set; }
    public int Stock { get; set; }

    //Favoritos y estado
    public bool IsFavorite { get; set; } = false;

    //Opcionales
    public string? WeightOrMeasure { get; set; }
    public string? Color { get; set; }
    public string? Model { get; set; }
}